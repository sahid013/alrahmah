"""
Convert the masjid's yearly prayer timetable spreadsheet into
src/lib/prayer-timetable-<year>.ts (used by src/lib/prayer-times.ts).

Usage (needs Python 3 + openpyxl):
    python3 scripts/import-prayer-timetable.py "data/prayer-timetables/WEBSITE 2026.xlsx" 2026

Reads the sheet named "Sheet1" with columns:
    DATE | FAJR START | FAJR JAMAT | SUNRISE | DHUHR START | DHUHR JAMAT |
    ASR START | ASR JAMAT | MAGHRIB | ISHA START | ISHA JAMAT
Times are local (UK) clock times. Only day + month of DATE are used, so a template whose
dates say another year still works; 29 February is skipped in non-leap years.
"""
import calendar
import datetime
import re
import sys

import openpyxl

COLUMNS = ['fajr', 'fajrJamaah', 'sunrise', 'dhuhr', 'dhuhrJamaah', 'asr', 'asrJamaah',
           'maghrib', 'isha', 'ishaJamaah']


def hhmm(value):
    if isinstance(value, (datetime.time, datetime.datetime)):
        return value.strftime('%H:%M')
    match = re.match(r'^\s*(\d{1,2}):(\d{2})', str(value or ''))
    if not match:
        raise ValueError(f'Unreadable time: {value!r}')
    return f'{int(match.group(1)):02d}:{match.group(2)}'


def main(path, year):
    sheet = openpyxl.load_workbook(path, data_only=True)['Sheet1']
    days = {}
    for row in sheet.iter_rows(min_row=2, values_only=True):
        if not isinstance(row[0], datetime.datetime):
            continue
        month, day = row[0].month, row[0].day
        if (month, day) == (2, 29) and not calendar.isleap(year):
            continue
        days[f'{month:02d}-{day:02d}'] = ' '.join(hhmm(v) for v in row[1:11])
    expected = 366 if calendar.isleap(year) else 365
    if len(days) != expected:
        raise SystemExit(f'Expected {expected} days, found {len(days)}')

    lines = [
        '// GENERATED by scripts/import-prayer-timetable.py from the masjid\'s published timetable',
        f'// ({path.split("/")[-1]}, sheet "Sheet1"). Do not edit by hand: re-run the script.',
        '//',
        '// One entry per day ("MM-DD"), UK local clock times, space-separated in this order:',
        '// ' + ' '.join(COLUMNS),
        f'export const PRAYER_TIMETABLE_{year}: Record<string, string> = {{',
    ]
    lines += [f"  '{key}': '{value}'," for key, value in sorted(days.items())]
    lines.append('};')
    out = f'src/lib/prayer-timetable-{year}.ts'
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'Wrote {out} ({len(days)} days)')


if __name__ == '__main__':
    main(sys.argv[1], int(sys.argv[2]))
